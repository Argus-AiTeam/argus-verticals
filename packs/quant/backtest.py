"""Backtest contract and forced-ledger executor, adapted from the Argus quant vertical.

The real backtest engine and data belong to the task, not to this pack. This
module defines the thin contract that lets the run stage drive *some* engine
and have every trial captured in the search ledger:

* :class:`BacktestEngine` — a ``Protocol``; any object with ``name`` and
  ``run(spec) -> BacktestResult`` qualifies, no subclassing.
* :func:`run_backtest` — runs the engine and appends the result, success or
  failure, to the :class:`~search_ledger.SearchLedger` at the execution
  boundary, so search breadth is recorded by construction rather than
  back-filled.
* :class:`ForcingExecutor` — the :class:`BacktestExecutor` to hand the factor
  loop instead of a raw engine: its only surface is ``submit(spec)``, which
  goes through :func:`run_backtest`, so no trial can bypass the ledger.

This is evidence capture, not a review gate: nothing here decides whether a
factor is good. The Reviewer reads the ledger and the report and rules.

Use from Python with this folder on ``sys.path``::

    import sys; sys.path.insert(0, "<this folder>")
    from backtest import BacktestSpec, ForcingExecutor
    from search_ledger import SearchLedger
"""
from __future__ import annotations

import threading
import time
import traceback
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from typing import Any, Protocol, runtime_checkable

from search_ledger import LedgerRow, SearchLedger


@dataclass(frozen=True)
class BacktestSpec:
    """A single trial to run.

    Carries both *what* to test and the reproducibility context an auditor needs
    to re-run it. ``run_id`` is generated by the caller *before* execution so a
    crashed run still leaves a ledger row referencing it.
    """

    run_id: str
    factor_ids: Sequence[str]
    # "single" | "equal_weight" | "optimized" | ... — how factors are combined.
    weighting: str = "single"
    # Optimization inputs / combination weights, screen params, etc.
    params: Mapping[str, Any] = field(default_factory=dict)
    # Evaluation window label, e.g. "train", "validation", "test", or a
    # walk-forward window id. Drives the oos/is interpretation downstream.
    window: str = ""
    is_out_of_sample: bool = False
    # Reproducibility context: metrics without this are not auditable.
    universe: str = ""
    data_snapshot: str = ""
    seed: int | None = None


@dataclass(frozen=True)
class BacktestResult:
    """The outcome of one trial.

    ``metrics`` holds the numbers the analysis stage reads (IC, RankIC, ICIR,
    long-short return, turnover, cost-adjusted return, ...). ``status`` is
    ``"ok"`` on success or ``"error"`` on failure; ``warnings`` surfaces
    partial-failure / data-coverage caveats. ``engine`` identifies the engine
    build so a result can be reproduced. Put the applied cost model in
    ``metadata`` (e.g. ``cost_model_id``, ``net_of_cost``) so
    ``run.cost_model_applied`` can be checked from the ledger.
    """

    run_id: str
    status: str = "ok"
    metrics: Mapping[str, float] = field(default_factory=dict)
    engine: str = ""
    warnings: Sequence[str] = field(default_factory=tuple)
    error: str = ""
    metadata: Mapping[str, Any] = field(default_factory=dict)


@runtime_checkable
class BacktestEngine(Protocol):
    """The contract a real backtest engine must satisfy."""

    name: str

    def run(self, spec: BacktestSpec) -> BacktestResult:
        ...


def _result_payload(spec: BacktestSpec, result: BacktestResult) -> dict[str, Any]:
    """Flatten a spec+result into a ledger row payload (audit-complete)."""
    return {
        "run_id": spec.run_id,
        "factor_ids": list(spec.factor_ids),
        "weighting": spec.weighting,
        "params": dict(spec.params),
        "window": spec.window,
        "is_out_of_sample": spec.is_out_of_sample,
        "universe": spec.universe,
        "data_snapshot": spec.data_snapshot,
        "seed": spec.seed,
        "status": result.status,
        "metrics": dict(result.metrics),
        "engine": result.engine,
        "warnings": list(result.warnings),
        "error": result.error,
        "metadata": dict(result.metadata),
    }


def run_backtest(
    engine: BacktestEngine, spec: BacktestSpec, ledger: SearchLedger
) -> tuple[BacktestResult, LedgerRow]:
    """Run one trial and record it in the ledger at the execution boundary.

    Returns the engine's result and the ledger row written for it. A raised
    exception from the engine is caught, converted to an ``"error"`` result, and
    *still logged* — so a failed trial cannot silently vanish from the search
    breadth. The exception is not re-raised; callers inspect ``result.status``.
    """
    started = time.time()
    try:
        result = engine.run(spec)
    except Exception as exc:  # noqa: BLE001 - failures must be recorded, not lost
        result = BacktestResult(
            run_id=spec.run_id,
            status="error",
            engine=getattr(engine, "name", ""),
            error=f"{type(exc).__name__}: {exc}",
            warnings=(traceback.format_exc().strip(),),  # the reviewer audits the whole stack
        )
    payload = _result_payload(spec, result)
    payload["elapsed_s"] = round(time.time() - started, 6)
    return result, ledger.append(payload)


@runtime_checkable
class BacktestExecutor(Protocol):
    """The single execution surface the factor loop is given.

    A caller cannot reach the underlying engine from this Protocol. Every
    invocation results in a ledger row by construction.
    """

    def submit(self, spec: BacktestSpec) -> tuple[BacktestResult, LedgerRow]:
        ...


@dataclass
class ForcingExecutor:
    """Reference :class:`BacktestExecutor` that funnels every trial through the ledger.

    A successful return from :meth:`submit` implies a ledger row was fsynced; an
    engine exception becomes a ``status="error"`` row. A lock serialises writes
    so in-process parallel submitters share one ledger; separate processes need
    a ledger file each.
    """

    engine: BacktestEngine
    ledger: SearchLedger
    _lock: threading.Lock = field(default_factory=threading.Lock, init=False, repr=False)

    def __post_init__(self) -> None:
        if not isinstance(self.engine, BacktestEngine):
            raise TypeError(
                f"engine {self.engine!r} does not implement BacktestEngine "
                f"(missing 'name' or 'run'?)"
            )

    def submit(self, spec: BacktestSpec) -> tuple[BacktestResult, LedgerRow]:
        with self._lock:
            return run_backtest(self.engine, spec, self.ledger)

    @property
    def trials_recorded(self) -> int:
        """The number of rows in the ledger — the trial count the multiple-testing haircut needs."""
        return len(self.ledger)
